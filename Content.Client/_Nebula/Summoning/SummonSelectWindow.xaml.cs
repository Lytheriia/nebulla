using Content.Client.UserInterface.Controls;
using Content.Shared._Nebula.Summoning;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Nebula.Summoning;

[GenerateTypedNameReferences]
public sealed partial class SummonSelectWindow : FancyWindow
{
    public event Action<NetEntity>? OnSelect;

    private NetEntity? _selected;

    public SummonSelectWindow()
    {
        RobustXamlLoader.Load(this);

        Candidates.OnItemSelected += args =>
        {
            _selected = (NetEntity) Candidates[args.ItemIndex].Metadata!;
            OkButton.Disabled = false;
        };
        Candidates.OnItemDeselected += _ =>
        {
            _selected = null;
            OkButton.Disabled = true;
        };

        OkButton.OnPressed += _ =>
        {
            if (_selected is { } selected)
                OnSelect?.Invoke(selected);
        };
        CancelButton.OnPressed += _ => Close();
    }

    public void SetCandidates(List<SummonCandidate> candidates)
    {
        Candidates.Clear();
        _selected = null;
        OkButton.Disabled = true;

        foreach (var candidate in candidates)
        {
            Candidates.AddItem(candidate.Label).Metadata = candidate.Entity;
        }
    }
}
