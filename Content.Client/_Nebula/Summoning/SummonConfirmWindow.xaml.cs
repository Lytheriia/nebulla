using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;
using Timer = Robust.Shared.Timing.Timer;

namespace Content.Client._Nebula.Summoning;

[GenerateTypedNameReferences]
public sealed partial class SummonConfirmWindow : FancyWindow
{
    public event Action<bool>? OnChoice;

    public SummonConfirmWindow()
    {
        RobustXamlLoader.Load(this);

        AcceptButton.OnPressed += _ => OnChoice?.Invoke(true);
        DenyButton.OnPressed += _ => OnChoice?.Invoke(false);
    }

    public void SetContent(string title, string text, TimeSpan delay)
    {
        Title = title;
        TextLabel.SetMessage(FormattedMessage.FromUnformatted(text));

        if (delay <= TimeSpan.Zero)
        {
            EnableButtons();
            return;
        }

        Timer.Spawn(delay, EnableButtons);
    }

    /// <summary>
    /// Locks the buttons while the server handles the answer.
    /// </summary>
    public void DisableButtons()
    {
        AcceptButton.Disabled = true;
        DenyButton.Disabled = true;
    }

    private void EnableButtons()
    {
        AcceptButton.Disabled = false;
        DenyButton.Disabled = false;
    }
}
