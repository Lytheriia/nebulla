using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Nebula.Summoning;

[GenerateTypedNameReferences]
public sealed partial class SummonRefusalWindow : FancyWindow
{
    public event Action<string>? OnSend;

    public SummonRefusalWindow()
    {
        RobustXamlLoader.Load(this);

        ReasonEdit.OnTextEntered += args => OnSend?.Invoke(args.Text);
        SendButton.OnPressed += _ => OnSend?.Invoke(ReasonEdit.Text);
    }

    public void FocusInput()
    {
        ReasonEdit.GrabKeyboardFocus();
    }
}
