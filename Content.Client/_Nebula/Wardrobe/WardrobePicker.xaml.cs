using System.Linq;
using Content.Client._Nebula.Sponsor;
using Content.Shared._Nebula.Wardrobe;
using Content.Shared.Preferences;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Nebula.Wardrobe;

/// <summary>
/// Wardrobe tab of the profile editor, with a tab for every wardrobe category.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class WardrobePicker : Control
{
    [Dependency] private IEntityManager _entMan = default!;
    [Dependency] private IPrototypeManager _proto = default!;

    private readonly List<WardrobeCategory> _categories = [];
    private SponsorSystem? _sponsors;

    public event Action<EntProtoId, bool>? Toggled;

    /// <summary>
    /// Raised when the Boosty rank changes and availability of the items has to be refreshed.
    /// </summary>
    public event Action? TierUpdated;

    public int? Rank => _sponsors?.Rank;

    public WardrobePicker()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        var sprite = _entMan.System<SpriteSystem>();
        foreach (var proto in _proto.EnumeratePrototypes<WardrobeCategoryPrototype>().OrderBy(c => c.Order))
        {
            var category = new WardrobeCategory(proto, _proto, sprite);
            category.Toggled += (item, pressed) => Toggled?.Invoke(item, pressed);
            CategoryTabs.AddChild(category);
            TabContainer.SetTabTitle(category, Loc.GetString(proto.Name));
            _categories.Add(category);
        }
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();

        _sponsors = _entMan.System<SponsorSystem>();
        _sponsors.StatusChanged += OnTierUpdated;
        _sponsors.RequestStatus();
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();

        if (_sponsors != null)
            _sponsors.StatusChanged -= OnTierUpdated;
    }

    private void OnTierUpdated()
    {
        TierUpdated?.Invoke();
    }

    public void Refresh(HumanoidCharacterProfile profile)
    {
        foreach (var category in _categories)
        {
            category.Refresh(profile, Rank);
        }
    }
}
